"""Development tools for openGym on Pebble.

    uv run pebbleopengym names [--repo PATH] [--lang en,de]
        Regenerates src/pkjs/exercise_names.js from the openGym exercise catalogue, from a local
        clone of github.com/DuarteSantos8/openGym or downloaded from GitHub.

    uv run pebbleopengym mock-server [--port 8787] [--token ogt_test]
        A stand-in for the openGym token API (GET/PUT /api/token/data) with a small profile,
        for trying the app in the emulator without a real server.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NAMES_OUT = ROOT / "src" / "pkjs" / "exercise_names.js"
RAW = "https://raw.githubusercontent.com/DuarteSantos8/openGym/{ref}/{path}"
EN_FILE = "frontend/src/lib/exercises-data.js"
LANG_FILE = "frontend/src/exercise-names/{lang}.js"


def _read_source(repo: Path | None, ref: str, path: str) -> str:
    if repo:
        return (repo / path).read_text(encoding="utf-8")
    url = RAW.format(ref=ref, path=path)
    print(f"downloading {url}", file=sys.stderr)
    with urllib.request.urlopen(url, timeout=60) as resp:
        return resp.read().decode("utf-8")


def _json_parse_literal(source: str, name: str, export: str = ""):
    """The value of a `JSON.parse('...')` in a generated catalogue module (the first one, or the
    one assigned to `export`)."""
    prefix = rf"{re.escape(export)}\s*=\s*" if export else ""
    m = re.search(prefix + r"JSON\.parse\('((?:[^'\\]|\\.)*)'\)", source, re.S)
    if not m:
        raise SystemExit(f"{name}: no JSON.parse('...') found")
    # A JS single-quoted string uses the same escapes Python's does for this content.
    return json.loads(ast.literal_eval("'" + m.group(1) + "'"))


def build_names(repo: Path | None, ref: str, langs: list[str]) -> dict[str, dict[str, str]]:
    en_source = _read_source(repo, ref, EN_FILE)
    exdb = _json_parse_literal(en_source, EN_FILE, "EXDB")
    out: dict[str, dict[str, str]] = {}
    # Variant ids (a female-model clip of the same lift) stand for the exercise they draw.
    out["alias"] = {str(k): str(v) for k, v in _json_parse_literal(en_source, EN_FILE, "EXALIAS").items()}
    en = {}
    for ex in exdb:
        if ex.get("id") is not None and ex.get("n"):
            n = ex["n"]
            en[str(ex["id"])] = n[:1].upper() + n[1:]
    out["en"] = en
    for lang in langs:
        if lang == "en":
            continue
        path = LANG_FILE.format(lang=lang)
        out[lang] = {str(k): v for k, v in _json_parse_literal(_read_source(repo, ref, path), path).items() if v}
    return out


def cmd_names(args: argparse.Namespace) -> None:
    langs = [x.strip() for x in args.lang.split(",") if x.strip()]
    table = build_names(Path(args.repo) if args.repo else None, args.ref, langs)
    body = json.dumps(table, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    NAMES_OUT.write_text(
        "// Generated by `uv run pebbleopengym names` from the openGym exercise catalogue\n"
        "// (github.com/DuarteSantos8/openGym, AGPL-3.0). Do not edit.\n"
        f"module.exports = {body};\n",
        encoding="utf-8",
    )
    sizes = ", ".join(f"{k}: {len(v)}" for k, v in table.items())
    print(f"wrote {NAMES_OUT.relative_to(ROOT)} ({NAMES_OUT.stat().st_size // 1024} KB; {sizes})")


def cmd_mock_server(args: argparse.Namespace) -> None:
    from .mock_server import serve

    serve(args.port, args.token)


def main() -> None:
    parser = argparse.ArgumentParser(prog="pebbleopengym", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("names", help="regenerate the bundled exercise names")
    p.add_argument("--repo", help="local clone of the openGym repository (default: download)")
    p.add_argument("--ref", default="main", help="git ref to download from (default: main)")
    p.add_argument("--lang", default="en,de", help="languages to bundle (default: en,de)")
    p.set_defaults(func=cmd_names)

    p = sub.add_parser("mock-server", help="a fake openGym token API for the emulator")
    p.add_argument("--port", type=int, default=8787)
    p.add_argument("--token", default="ogt_test")
    p.set_defaults(func=cmd_mock_server)

    args = parser.parse_args()
    args.func(args)
